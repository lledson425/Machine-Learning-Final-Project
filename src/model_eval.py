import pandas as pd

class ModelEvaluator:
    def __init__(
        self,
        token_to_id,
        id_to_token,
        generate_solution_fn,
        tokens_to_string_fn
    ):
        self.token_to_id = token_to_id
        self.id_to_token = id_to_token
        self.generate_solution = generate_solution_fn
        self.tokens_to_string = tokens_to_string_fn

    def check_syntax_with_reason(self, output):
        if output is None or output.strip() == "":
            return False, "empty_output"

        output = output.strip()

        steps = [step.strip() for step in output.split("->") if step.strip()]

        if len(steps) == 0:
            return False, "no_steps"

        operators = set("+-*/^")

        for step in steps:

            # check exactly one equals sign
            if step.count("=") == 0:
                return False, "missing_equals_sign"

            if step.count("=") > 1:
                return False, "too_many_equals_signs"

            # check parentheses are balanced
            stack = []

            for char in step:
                if char == "(":
                    stack.append(char)
                elif char == ")":
                    if not stack:
                        return False, "extra_closing_parenthesis"
                    stack.pop()

            if stack:
                return False, "unclosed_parenthesis"

            # check operator order
            prev = None

            for i, char in enumerate(step):
                if char in operators:

                    # allow leading negative sign
                    if char == "-" and (i == 0 or step[i - 1] in "(="):
                        prev = char
                        continue

                    # operator cannot be first
                    if i == 0:
                        return False, "operator_at_start"

                    # operator cannot be last
                    if i == len(step) - 1:
                        return False, "operator_at_end"

                    # operator cannot come right after another operator
                    if prev in operators:
                        return False, "double_operator"

                    # operator cannot come right before another operator,
                    # except a negative sign, like x*-2
                    next_char = step[i + 1]

                    if next_char in operators and next_char != "-":
                        return False, "bad_operator_sequence"

                prev = char

        return True, "valid"

    def normalize_text(self, s):
        if s is None:
            return ""

        return str(s).replace(" ", "").strip()

    def evaluate_model(
        self,
        model,
        df,
        input_col,
        target_col=None,
        category_col="type",
        num_examples=100,
        max_new_tokens=30,
        temperature=2,
        greedy=True,
        random_state=0
    ):

        sample_df = df.sample(
            min(num_examples, len(df)),
            random_state=random_state
        ).copy()

        results = []

        for _, row in sample_df.iterrows():

            prompt = row[input_col]

            generated = self.generate_solution(
                model,
                prompt,
                self.token_to_id,
                self.id_to_token,
                max_new_tokens=max_new_tokens,
                temperature=temperature,
                greedy=greedy
            )

            output = self.tokens_to_string(generated)

            syntax_correct, syntax_reason = self.check_syntax_with_reason(output)

            if target_col is not None:
                target = row[target_col]
                exact_match = self.normalize_text(output) == self.normalize_text(target)
            else:
                target = None
                exact_match = None

            if category_col is not None:
                category = row[category_col]
            else:
                category = None

            results.append({
                "category": category,
                "input": prompt,
                "target": target,
                "generated": output,
                "syntax_correct": syntax_correct,
                "syntax_reason": syntax_reason,
                "exact_match": exact_match
            })

        results_df = pd.DataFrame(results)

        return results_df

    def summarize_results(self, results_df):

        print("=" * 80)
        print("OVERALL RESULTS")
        print("=" * 80)

        print("Number of examples:", len(results_df))
        print("Syntax accuracy:", results_df["syntax_correct"].mean())

        if results_df["exact_match"].notna().any():
            print("Exact match accuracy:", results_df["exact_match"].mean())

        print("\n" + "=" * 80)
        print("RESULTS BY CATEGORY")
        print("=" * 80)

        summary = results_df.groupby("category").agg(
            num_examples=("input", "count"),
            syntax_accuracy=("syntax_correct", "mean"),
            exact_match_accuracy=("exact_match", "mean")
        )

        print(summary)

        return summary

    def summarize_syntax_errors(self, results_df):
        total = len(results_df)
        num_valid = results_df["syntax_correct"].sum()
        num_invalid = total - num_valid

        print("\n" + "=" * 80)
        print("MOST COMMON SYNTAX ERRORS")
        print("=" * 80)

        error_counts = (
            results_df[results_df["syntax_correct"] == False]["syntax_reason"]
            .value_counts()
            .reset_index()
        )

        error_counts.columns = ["syntax_error", "count"]

        if num_invalid > 0:
            error_counts["percent_of_errors"] = error_counts["count"] / num_invalid
        else:
            error_counts["percent_of_errors"] = 0

        error_counts["percent_of_total"] = error_counts["count"] / total

        print(error_counts.to_string(index=False))

        return error_counts